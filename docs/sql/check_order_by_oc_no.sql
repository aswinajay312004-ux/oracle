-- POPPYS AI: check one order straight from Oracle in SQL Developer.
-- Read-only (SELECT only); nothing is changed.
-- 1. Open SQL Developer and the GARMENT_DEMO connection.
-- 2. Open this file (File > Open) or paste it in the worksheet.
-- 3. Press F5 (Run Script). SQL Developer asks for OC_NO: type the OC No exactly as on
--    the POPPYS Saved screen, for example PK/26-27/S/1.
-- The same queries for one order, with the expected results next to them, are on the
-- POPPYS website: Database > Orders > the order > "Check in SQL Developer".
-- Tables and columns: the GARMENT_DEMO write mapping (backend/erp/mapping.py).

SET DEFINE ON
DEFINE OC_NO = '&OC_NO'

-- 1. The order (header), names instead of record IDs
SELECT o.ORDMASID, o.DOCID AS OC_NO, o.ODATE AS ORDER_DATE, b.BUYERNAME AS BUYER, sn.STYLENUMBER AS STYLE,
       sm.SDESC AS DESCRIPTION, o.BONO AS PO_NO, mr.NAME AS MERCHANDISER, u.UOM AS UNIT, o.OQTY AS TOTAL_PIECES,
       o.SAMPLETYPE, o.ORDCATEGORY, o.REMARKS
FROM GARMENT_DEMO.ORDMAS o
LEFT JOIN GARMENT_DEMO.BUYMAS b ON b.BUYMASID = o.BUYER
LEFT JOIN GARMENT_DEMO.STYLENUM sn ON sn.STYLENUMID = o.STYLENO
LEFT JOIN GARMENT_DEMO.STYLEMAS sm ON sm.STYLEMASID = o.STYLEDESC
LEFT JOIN GARMENT_DEMO.MERCHMAS mr ON mr.MERCHMASID = o.MERCH
LEFT JOIN GARMENT_DEMO.UNITMAS u ON u.UNITMASID = o.UOM
WHERE o.DOCID = '&OC_NO';

-- 2. Colour lines
SELECT l.SNO AS LINE_NO, c.COLOR AS COLOUR, l.ORDQTY AS PIECES, l.SHIPDT AS SHIP_DATE, l.PONUM AS PO_NO, l.SUBNO
FROM GARMENT_DEMO.ORDSTYLE l
JOIN GARMENT_DEMO.ORDMAS o ON o.ORDMASID = l.ORDMASID
LEFT JOIN GARMENT_DEMO.COLORMAS c ON c.COLORMASID = l.COMBO
WHERE o.DOCID = '&OC_NO'
ORDER BY l.SNO;

-- 3. Colour x size, one row per colour (like the Excel)
SELECT c.COLOR AS COLOUR,
       LISTAGG(z.SIZES || ' = ' || s.RQTY, '  |  ') WITHIN GROUP (ORDER BY s.ORDSIZEROW) AS SIZE_QUANTITIES,
       SUM(s.RQTY) AS PIECES
FROM GARMENT_DEMO.ORDSIZE s
JOIN GARMENT_DEMO.ORDMAS o ON o.ORDMASID = s.ORDMASID
JOIN GARMENT_DEMO.ORDSTYLE l ON l.ORDMASID = s.ORDMASID AND l.SUBNO = s.SUB3_SUBNO
LEFT JOIN GARMENT_DEMO.COLORMAS c ON c.COLORMASID = l.COMBO
LEFT JOIN GARMENT_DEMO.SIZE_MAS z ON z.SIZE_MASID = s.GSIZE
WHERE o.DOCID = '&OC_NO'
GROUP BY l.SNO, c.COLOR
ORDER BY l.SNO;

-- 4. Totals check: HEADER_TOTAL and SIZE_TOTAL must be the same number
SELECT o.DOCID AS OC_NO, o.OQTY AS HEADER_TOTAL,
       (SELECT COUNT(*) FROM GARMENT_DEMO.ORDSTYLE l WHERE l.ORDMASID = o.ORDMASID) AS COLOUR_LINES,
       (SELECT COUNT(*) FROM GARMENT_DEMO.ORDSIZE s WHERE s.ORDMASID = o.ORDMASID) AS SIZE_ROWS,
       (SELECT SUM(s.RQTY) FROM GARMENT_DEMO.ORDSIZE s WHERE s.ORDMASID = o.ORDMASID) AS SIZE_TOTAL
FROM GARMENT_DEMO.ORDMAS o
WHERE o.DOCID = '&OC_NO';

-- 5. The last 20 orders, newest first (to find an OC No)
SELECT * FROM (
  SELECT o.ORDMASID, o.DOCID AS OC_NO, o.ODATE AS ORDER_DATE, b.BUYERNAME AS BUYER, o.BONO AS PO_NO, o.OQTY AS TOTAL_PIECES
  FROM GARMENT_DEMO.ORDMAS o LEFT JOIN GARMENT_DEMO.BUYMAS b ON b.BUYMASID = o.BUYER
  ORDER BY o.ORDMASID DESC
) WHERE ROWNUM <= 20;
