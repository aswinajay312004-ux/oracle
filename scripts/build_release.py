"""Builds an OFFLINE release folder for the Windows laptop. Run on any computer WITH internet (any OS):

    python scripts/build_release.py [--out dist] [--python-installer 3.13.x]

Produces dist/poppys-ai-<version>/ and a .zip of it:
  app files          every file git tracks, except tests and developer-only folders
  wheelhouse/        Windows (win_amd64, CPython 3.13) wheels for requirements.txt and all their dependencies
  wheelhouse/requirements.lock   name==version --hash=sha256:… for every wheel (pip --require-hashes)
  installers/        optional: the python.org installer for the given 3.13.x version
  SHA256SUMS         every file above (sha256sum format; install-service.ps1 refuses a changed release)

On the laptop (no internet):  .\\setup.ps1 -Offline
"""
from __future__ import annotations
import argparse
import hashlib
import re
import shutil
import subprocess
import sys
import urllib.request
import zipfile
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKIP = ('tests/', '.github/', 'docs/video_analysis/', 'notes/')
PLATFORM, PYVER = 'win_amd64', '3.13'


def sh(*cmd, **kw):
    print('  $', ' '.join(map(str, cmd)))
    return subprocess.run(cmd, check=True, text=True, capture_output=True, **kw).stdout


def sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def wheel_name(filename):
    """('python-calamine', '0.9.0') from 'python_calamine-0.9.0-cp313-cp313-win_amd64.whl'."""
    m = re.match(r'^(.+?)-(\d[^-]*)-', filename)
    return m.group(1).replace('_', '-').lower(), m.group(2)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default='dist')
    ap.add_argument('--python-installer', help='also download python-<version>-amd64.exe from python.org, e.g. 3.13.5')
    a = ap.parse_args()
    version = sh('git', '-C', str(ROOT), 'describe', '--always', '--dirty').strip() + '-' + datetime.now().strftime('%Y%m%d')
    if version.split('-')[-2:-1] == ['dirty']:
        print('WARNING: uncommitted changes are NOT included (only committed files are packaged).')
    out = (ROOT / a.out / f'poppys-ai-{version}').resolve()
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    print('== app files (git-tracked, committed)')
    files = [f for f in sh('git', '-C', str(ROOT), 'ls-files').splitlines() if not f.startswith(SKIP)]
    for f in files:
        target = out / f; target.parent.mkdir(parents=True, exist_ok=True)
        blob = subprocess.run(['git', '-C', str(ROOT), 'show', f'HEAD:{f}'], check=True, capture_output=True).stdout
        target.write_bytes(blob)
    print(f'   {len(files)} files')

    print('== Windows wheels for requirements.txt (binary only, no source builds)')
    wh = out / 'wheelhouse'; wh.mkdir()
    # pip evaluates dependency markers (sys_platform) for the computer it runs on, not for --platform. So the
    # Windows dependency set is resolved by uv for Windows, then each pinned wheel is downloaded without re-resolving.
    uv = shutil.which('uv')
    if uv:
        resolved = out / 'wheelhouse' / 'resolved.txt'
        sh(uv, 'pip', 'compile', str(out / 'requirements.txt'), '--python-platform', 'x86_64-pc-windows-msvc',
           '--python-version', PYVER, '--no-header', '--no-annotate', '-q', '-o', str(resolved))
        sh(sys.executable, '-m', 'pip', 'download', '--no-deps', '--only-binary=:all:', '--platform', PLATFORM,
           '--python-version', PYVER, '--implementation', 'cp', '-r', str(resolved), '-d', str(wh))
        resolved.unlink()
    elif sys.platform == 'win32':
        sh(sys.executable, '-m', 'pip', 'download', '--only-binary=:all:', '--platform', PLATFORM, '--python-version', PYVER,
           '--implementation', 'cp', '-r', str(out / 'requirements.txt'), '-d', str(wh))
    else:
        raise SystemExit('On a non-Windows computer the build needs uv to resolve the Windows packages: pip install uv')
    wheels = sorted(p for p in wh.iterdir() if p.suffix == '.whl')
    if not wheels:
        raise SystemExit('No wheels were downloaded.')
    lock = [f'{wheel_name(w.name)[0]}=={wheel_name(w.name)[1]} --hash=sha256:{sha256(w)}' for w in wheels]
    (wh / 'requirements.lock').write_text('# Generated by scripts/build_release.py; install with --no-index --require-hashes\n'
                                          + '\n'.join(lock) + '\n', encoding='utf-8')
    print(f'   {len(wheels)} wheels')

    if a.python_installer:
        print('== python.org installer')
        if not re.fullmatch(r'3\.13\.\d+', a.python_installer):
            raise SystemExit('--python-installer must be a 3.13.x version.')
        inst = out / 'installers'; inst.mkdir()
        url = f'https://www.python.org/ftp/python/{a.python_installer}/python-{a.python_installer}-amd64.exe'
        with urllib.request.urlopen(url, timeout=120) as r, open(inst / Path(url).name, 'wb') as f:
            shutil.copyfileobj(r, f)

    print('== SHA256SUMS')
    listed = sorted(p for p in out.rglob('*') if p.is_file())
    (out / 'SHA256SUMS').write_text(''.join(f'{sha256(p)}  {p.relative_to(out).as_posix()}\n' for p in listed), encoding='utf-8')

    print('== zip')
    archive = out.with_suffix('.zip')
    with zipfile.ZipFile(archive, 'w', zipfile.ZIP_DEFLATED) as z:
        for p in sorted(out.rglob('*')):
            if p.is_file():
                z.write(p, f'{out.name}/{p.relative_to(out).as_posix()}')
    print(f'Release ready: {archive}  ({archive.stat().st_size / 1e6:.1f} MB). Copy it to the laptop, unzip, then .\\setup.ps1 -Offline')


if __name__ == '__main__':
    main()
